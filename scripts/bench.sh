# Runs the pipeline benchmark and writes its output into docs/BENCHMARKS.md, between the
# bench-results markers. Counted metrics are deterministic. Timings depend on the machine and are
# informational only. Run from anywhere; the script moves to the repository root.
set -eu

cd "$(dirname "$0")/.."

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cargo bench -p tpt-thought-tests 2>/dev/null > "$work/raw"
awk '/^TPT Thought pipeline benchmark/ { found = 1 } found' "$work/raw" > "$work/body"
if [ ! -s "$work/body" ]; then
    echo "no benchmark output found" >&2
    exit 1
fi

awk -v body="$work/body" -v date="$(date -u +%Y-%m-%d)" '
    /<!-- bench-results:start -->/ {
        print
        print "Generated by `scripts/bench.sh` on " date "."
        print ""
        print "```text"
        while ((getline line < body) > 0) print line
        print "```"
        skip = 1
        next
    }
    /<!-- bench-results:end -->/ { skip = 0 }
    !skip { print }
' docs/BENCHMARKS.md > "$work/doc"

mv "$work/doc" docs/BENCHMARKS.md
echo "docs/BENCHMARKS.md updated."
