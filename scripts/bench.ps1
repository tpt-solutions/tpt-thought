# Runs the pipeline benchmark and writes its output into docs/BENCHMARKS.md, between the
# bench-results markers. Counted metrics are deterministic. Timings depend on the machine and are
# informational only. Run from anywhere; the script moves to the repository root.
$ErrorActionPreference = 'Stop'

Set-Location (Join-Path $PSScriptRoot '..')

$lines = @(cargo bench -p tpt-thought-tests 2>$null)
if ($LASTEXITCODE -ne 0) {
    throw "cargo bench failed with exit code $LASTEXITCODE"
}

$first = -1
for ($i = 0; $i -lt $lines.Count; $i++) {
    if ($lines[$i] -like 'TPT Thought pipeline benchmark*') {
        $first = $i
        break
    }
}
if ($first -lt 0) {
    throw 'no benchmark output found'
}
$body = ($lines[$first..($lines.Count - 1)] -join "`n").TrimEnd()

$date = (Get-Date).ToUniversalTime().ToString('yyyy-MM-dd')
$block = @(
    '<!-- bench-results:start -->',
    "Generated by ``scripts/bench.ps1`` on $date.",
    '',
    '```text',
    $body,
    '```',
    '<!-- bench-results:end -->'
) -join "`n"

$path = 'docs/BENCHMARKS.md'
$doc = Get-Content -Path $path -Raw
$pattern = '(?s)<!-- bench-results:start -->.*?<!-- bench-results:end -->'
$updated = [regex]::Replace($doc, $pattern, $block.Replace('$', '$$'))
Set-Content -Path $path -Value $updated -Encoding utf8 -NoNewline

Write-Host "$path updated."
